    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Captura el DNI escrito en la caja de búsqueda
    String dni = texto_dni.getText().trim();
    boolean existeReceta = false;

    try {
        // Busca directamente en recetas.txt si ya existe una receta para este DNI
        java.io.File archivoRec = new java.io.File("recetas.txt");
        if (archivoRec.exists()) {
            java.util.Scanner lectorRec = new java.util.Scanner(archivoRec.toPath());
            while (lectorRec.hasNextLine()) {
                String linea = lectorRec.nextLine();
                String[] datos = linea.split(",");
                if (datos.length >= 6 && datos[2].equals(dni)) {
                    // Rellena los campos automáticamente con los datos encontrados en la receta
                    texto_dni.setText(datos[2]);
                    lista_medicamento2.setSelectedItem(datos[3]); // O el nombre de tu combo de medicamento
                    texto_dosis1.setText(datos[4]);              // Dosis
                    texto_dosis.setText(datos[5]);               // Cantidad
                    existeReceta = true;
                    break;
                }
            }
            lectorRec.close();
        }

        if (existeReceta) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Receta encontrada y cargada para modificar!");
        } else {
            // Si no está en recetas, revisa al menos que exista en registros.txt
            boolean existeReg = false;
            java.io.File archivoReg = new java.io.File("registros.txt");
            if (archivoReg.exists()) {
                java.util.Scanner lectorReg = new java.util.Scanner(archivoReg.toPath());
                while (lectorReg.hasNextLine()) {
                    String[] datos = lectorReg.nextLine().split(",");
                    if (datos.length >= 8 && datos[2].equals(dni)) {
                        existeReg = true;
                        break;
                    }
                }
                lectorReg.close();
            }

            if (existeReg) {
                javax.swing.JOptionPane.showMessageDialog(this, "Paciente encontrado en registros pero sin receta previa. Ingresa sus datos.");
                texto_dni.setText(dni);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "El DNI no se encuentra registrado en el sistema.");
            }
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton2ActionPerformed

