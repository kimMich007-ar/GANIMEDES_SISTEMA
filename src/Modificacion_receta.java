    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String dni = texto_dni.getText().trim();
    String medicamento = lista_medicamento2.getSelectedItem().toString(); // Obtiene el medicamento seleccionado
    String dosis = texto_dosis1.getText().trim();                       // Obtiene el texto de la dosis
    String cantidad = texto_dosis.getText().trim();                     // Obtiene el texto de la cantidad

    try {
        // Busca el nombre y apellido actualizados del paciente en los registros
        String nombre = "", apellido = "";
        java.util.Scanner sc = new java.util.Scanner(new java.io.File("registros.txt"));
        while (sc.hasNextLine()) {
            String[] d = sc.nextLine().split(",");
            if (d.length >= 8 && d[2].equals(dni)) {
                nombre = d[0];
                apellido = d[1];
                break;
            }
        }
        sc.close();

        // Lee todas las recetas y desecha la anterior de este DNI para eliminarla
        java.util.List<String> lista = new java.util.ArrayList<>();
        java.io.File archivo = new java.io.File("recetas.txt");
        
        if (archivo.exists()) {
            java.util.Scanner sc2 = new java.util.Scanner(archivo);
            while (sc2.hasNextLine()) {
                String lin = sc2.nextLine();
                String[] d = lin.split(",");
                if (d.length >= 6 && d[2].equals(dni)) {
                    continue; // Salta la receta vieja para borrarla
                }
                lista.add(lin);
            }
            sc2.close();
        }

        // Añade la nueva receta actualizada a la lista
        lista.add(nombre + "," + apellido + "," + dni + "," + medicamento + "," + dosis + "," + cantidad);

        // Sobrescribe el archivo recetas.txt con la información actualizada
        java.io.PrintWriter pw = new java.io.PrintWriter("recetas.txt");
        for (String l : lista) {
            pw.println(l);
        }
        pw.close();

        javax.swing.JOptionPane.showMessageDialog(this, "¡Receta actualizada con éxito!");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton3ActionPerformed

